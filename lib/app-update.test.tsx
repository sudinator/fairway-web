import { ok, report, renderScreen } from "./screen-harness";
import React, { act } from "react";
import { APP_VERSION } from "./app-version";
import { checkAutomaticVersion, automaticUpdateState, requestAppUpdate, newerVersion, clearConfirmedUpdateNotice } from "./automatic-updates";
import { RegisterSW } from "../components/register-sw";
import { UpdateChecker } from "../components/app-update-checker";
async function main() {
  const oldFetch = globalThis.fetch;
  window.localStorage.clear();
  globalThis.fetch = (async () => ({ ok: true, json: async () => ({ version: APP_VERSION }) })) as any;
  window.sessionStorage.setItem("bnn-update-dismissed", "999.0.261102");
  const legacy = { "bnn_update_sessions_v1:round:old": '{"kind":"round","id":"old"}', "bnn_round_draft_v1": '{"round":{"status":"in_progress"}}', "bnn_device_scores:u:t:bnn_game_scores_g_p": '{"scores":[5]}' };
  for (const [k, v] of Object.entries(legacy)) window.localStorage.setItem(k, v);
  let registerCount = 0, updateCount = 0;
  const events = new window.EventTarget();
  Object.defineProperty(navigator, "serviceWorker", { configurable: true, value: { register: async (_url: string, options: any) => { registerCount++; ok(options.updateViaCache === "none", "registration rechecks the worker without HTTP cache"); return { update: async () => { updateCount++; }, active: { postMessage() {} } }; }, addEventListener: events.addEventListener.bind(events), removeEventListener: events.removeEventListener.bind(events) } });
  let banner!: ReturnType<typeof renderScreen>;
  await act(async () => { banner = renderScreen(<RegisterSW />); await new Promise(resolve => setTimeout(resolve, 5)); });
  ok(registerCount === 1 && updateCount === 1, "pending drafts do not prevent automatic registration/check");
  ok(banner.text === "", "current release has no update banner or correction checklist");
  ok(JSON.stringify(Object.fromEntries(Object.keys(legacy).map(k => [k, window.localStorage.getItem(k)]))) === JSON.stringify(legacy), "registration preserves legacy gates and pending scores byte for byte");
  await act(async () => { events.dispatchEvent(new window.Event("controllerchange")); });
  ok(banner.text === "", "controller transition alone does not create an update banner");
  globalThis.fetch = (async () => ({ ok: true, json: async () => ({ version: APP_VERSION }) })) as any;
  let settings!: ReturnType<typeof renderScreen>;
  await act(async () => { settings = renderScreen(<UpdateChecker />); await new Promise(resolve => setTimeout(resolve, 5)); });
  ok(settings.text.includes("You’re up to date."), "current version success is visible");
  ok(settings.text.includes("A banner appears") && !settings.text.includes("Updates are paused"), "unfinished rounds never create an update gate");
  ok(!settings.text.includes("Verify saved scores") && !settings.text.includes("Update to"), "no correction gate for current release");
  globalThis.fetch = (async () => ({ ok: true, json: async () => ({ version: "999.0.261101" }) })) as any;
  await act(async () => { settings.click("Check version"); await new Promise(resolve => setTimeout(resolve, 5)); });
  ok(settings.text.includes("999.0.261101") && settings.text.includes("Tap Update now"), "new deployment explains next-open behavior without restarting");
  const kept = window.localStorage.getItem("bnn_round_draft_v1");
  ok(kept === legacy.bnn_round_draft_v1, "version checks never modify draft data");
  globalThis.fetch = (async () => { throw new Error("offline"); }) as any;
  await act(async () => { await checkAutomaticVersion(); });
  ok(settings.text.includes("continue scoring") && !automaticUpdateState().checking, "offline check finishes with useful nonblocking feedback");
  globalThis.fetch = (async () => ({ ok: true, json: async () => ({ version: "" }) })) as any;
  await act(async () => { await checkAutomaticVersion(); });
  ok(automaticUpdateState().message.includes("Could not check"), "invalid version is not reported as success");
  let finish!: (result: any) => void, calls = 0;
  globalThis.fetch = (() => { calls++; return new Promise(resolve => { finish = resolve; }); }) as any;
  let first!: Promise<void>, second!: Promise<void>;
  act(() => { first = checkAutomaticVersion(); second = checkAutomaticVersion(); });
  ok(first === second && calls === 1, "overlapping checks share one request");
  await act(async () => { finish({ ok: true, json: async () => ({ version: APP_VERSION }) }); await first; });
  globalThis.fetch = (() => new Promise(() => {})) as any;
  await act(async () => { await checkAutomaticVersion(10); });
  ok(!automaticUpdateState().checking && automaticUpdateState().message.includes("Could not check"), "nonresponsive request is bounded and cannot gate scoring");
  globalThis.fetch = (async () => ({ ok: true, json: () => new Promise(() => {}) })) as any;
  await act(async () => { await checkAutomaticVersion(10); });
  ok(!automaticUpdateState().checking, "nonresponsive response body also ends the version check");
  ok(newerVersion("212.100.261102", "212.99.261102") && !newerVersion("212.9.261102", "212.99.261102"), "version ordering is numeric, never a downgrade");
  ok(!newerVersion("bad") && !newerVersion("999.0.261102<script>"), "invalid versions never create an update action");
  globalThis.fetch = (async () => ({ ok: true, json: async () => ({ version: "999.0.261102" }) })) as any;
  await act(async () => { await checkAutomaticVersion(); });
  ok(banner.text.includes("999.0.261102") && banner.text.includes("Update now"), "new release has a visible action despite legacy dismissal and pending rounds");
  ok(!banner.text.includes("Later") && !banner.text.includes("Dismiss") && banner.el.querySelectorAll("button").length === 1, "pending release offers Update now only, with no dismissal");
  await act(async () => { clearConfirmedUpdateNotice(); });
  ok(banner.text.includes("Update now") && settings.text.includes("Update now"), "result expiry cannot hide a pending update");
  globalThis.fetch = (async () => ({ ok: true, json: async () => ({ version: "999.1.261102" }) })) as any;
  await act(async () => { await checkAutomaticVersion(); });
  ok(banner.text.includes("999.1.261102"), "a subsequent release replaces the pending version without hiding its action");
  globalThis.fetch = (async () => { throw new Error("offline"); }) as any;
  await act(async () => { await requestAppUpdate(10, () => { throw new Error("must not navigate"); }); });
  ok(banner.text.includes("Update could not finish") && banner.text.includes(APP_VERSION) && !automaticUpdateState().updating, "offline update identifies installed version and allows retry");
  ok(automaticUpdateState().outcome?.status === 'failure' && automaticUpdateState().outcome?.phase === 'check', 'failed check has a structured retryable outcome');
  globalThis.fetch = (async () => ({ ok: true, json: async () => ({ version: "999.1.261102" }) })) as any;
  globalThis.fetch = (async () => ({ ok: true, json: async () => ({ version: APP_VERSION }) })) as any;
  await act(async () => { await checkAutomaticVersion(); });
  ok(banner.text === "", "a confirmed withdrawn release clears stale failure instead of leaving an actionless banner");
  globalThis.fetch = (async () => ({ ok: true, json: async () => ({ version: "999.1.261102" }) })) as any;
  await act(async () => { await checkAutomaticVersion(); });
  ok(banner.text.includes("999.1.261102") && banner.text.includes("Update now"), "a newer release reappears after withdrawal without any dismissal flag");
  let activationMessages = 0;
  const workerEvents = new window.EventTarget();
  const installing: any = { state: "installing", addEventListener: workerEvents.addEventListener.bind(workerEvents), removeEventListener: workerEvents.removeEventListener.bind(workerEvents), postMessage: () => { activationMessages++; installing.state = "activated"; workerEvents.dispatchEvent(new window.Event("statechange")); } };
  (navigator.serviceWorker as any).getRegistration = async () => ({ update: async () => {}, installing });
  let prematureNavigation = false;
  await act(async () => { await requestAppUpdate(10, () => { prematureNavigation = true; }); });
  installing.state = "installed";workerEvents.dispatchEvent(new window.Event("statechange"));
  ok(!prematureNavigation && activationMessages === 0 && !automaticUpdateState().updating, "installation timeout removes listener: no delayed activation or navigation after failure");
  ok(automaticUpdateState().outcome?.phase === 'download', 'installation timeout identifies the download/installation phase');
  (navigator.serviceWorker as any).getRegistration = async () => ({ update: async () => {}, waiting: installing });
  await act(async () => { await requestAppUpdate(10, () => {}); });
  ok(activationMessages === 1 && installing.state === "activated", "explicit action activates a waiting worker before navigation");
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 15)); });
  let navigated = "", manualChecks = 0;
  (navigator.serviceWorker as any).getRegistration = async () => ({ update: async () => { manualChecks++; } });
  await act(async () => { await requestAppUpdate(15, url => { navigated = url; }); });
  ok(new URL(navigated).searchParams.get("bnnUpdate") === "999.1.261102" && new URL(navigated).searchParams.has("bnnUpdateAt") && manualChecks === 1, "explicit update checks worker and uses a fresh same-origin URL with target version");
  ok(automaticUpdateState().updating && !banner.text.includes("Updated successfully"), "navigation alone is not success");
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 25)); });
  ok(!automaticUpdateState().updating && banner.text.includes("did not restart"), "stalled navigation produces retry feedback");
  ok(automaticUpdateState().outcome?.phase === 'restart', 'stalled navigation identifies the restart phase');
  banner.unmount();
  // Bootstrap old/current versions using the real component; no score mutations.
  window.sessionStorage.setItem("bnn-update-attempt", "999.1.261102");
  await act(async () => { banner = renderScreen(<RegisterSW />); await new Promise(resolve => setTimeout(resolve, 5)); });
  ok(banner.text.includes("Update did not complete") && !banner.text.includes("Updated successfully"), "old shell after restart is reported as failure");
  banner.unmount();
  window.sessionStorage.setItem("bnn-update-attempt", APP_VERSION);
  await act(async () => { banner = renderScreen(<RegisterSW />); await new Promise(resolve => setTimeout(resolve, 5)); });
  ok(banner.text.includes("Updated successfully") && banner.text.includes(APP_VERSION), "restart success names actual running version");
  ok(automaticUpdateState().outcome?.status === 'success' && automaticUpdateState().outcome?.runningVersion === APP_VERSION, 'only verified running version records update success');
  ok(Object.entries(legacy).every(([k, v]) => window.localStorage.getItem(k) === v), "failure/retry/re-entry/success preserve every score/draft string");
  globalThis.fetch = (async () => ({ ok: true, json: async () => ({ version: APP_VERSION }) })) as any;
  const originalTimer = window.setTimeout;
  let expireSuccess: (() => void) | undefined;
  window.setTimeout = ((handler: TimerHandler, timeout?: number, ...args: any[]) => {
    if (timeout === 8000 && typeof handler === "function") expireSuccess = () => Reflect.apply(handler, window, args);
    return Reflect.apply(originalTimer, window, [handler, timeout, ...args]);
  }) as unknown as typeof window.setTimeout;
  await act(async () => { await checkAutomaticVersion(); });
  ok(typeof expireSuccess === "function", "confirmed success schedules the actual eight-second expiry effect");
  await act(async () => { expireSuccess?.(); });
  ok(banner.text === "", "confirmed success expires through the real component effect when no update is pending");
  ok(settings.text.includes('Last update attempt') && settings.text.includes(`Updated successfully to version ${APP_VERSION}`), 'settings retain verified success after the transient banner expires');
  window.setTimeout = originalTimer;
  window.localStorage.setItem("bnn_verified_score_recovery:old", '{"backup":{"scores":[6]}}');
  settings.unmount();
  globalThis.fetch = (async () => ({ ok: true, json: async () => ({ version: APP_VERSION }) })) as any;
  await act(async () => { settings = renderScreen(<UpdateChecker />); await new Promise(resolve => setTimeout(resolve, 5)); });
  ok(settings.text.includes("Download recovery copies"), "prior recovery copies remain accessible without an update gate");
  const beforeProtected = JSON.stringify(Object.fromEntries(Object.keys(legacy).map(k => [k, window.localStorage.getItem(k)])));
  for (const response of [
    { ok: false, status: 401 }, { ok: false, status: 403 },
    { ok: false, status: 0, type: "opaqueredirect" },
    { ok: true, redirected: true },
    { ok: true, headers: { get: () => "text/html" } },
  ]) {
    globalThis.fetch = (async (_url: any, options: any) => {
      ok(options.redirect === "manual" && options.credentials === "same-origin", "protected checks use own cookies without following login redirects");
      return response;
    }) as any;
    await act(async () => { await checkAutomaticVersion(); });
    ok(automaticUpdateState().checkFailure === "access" && settings.text.includes("Deployment access is required"), "access failure is distinct from offline");
    ok(settings.el.querySelector('a[href="/auth/deployment-access"]') != null, "explicit same-origin recovery link is available");
    ok(banner.text.includes("Reconnect to app"), "deployment access failure has a visible recovery banner");
    ok(settings.text.includes("Last attempt:"), "failure records an attempted check");
  }
  globalThis.fetch = (async () => ({ ok: false, status: 503 })) as any;
  await act(async () => { await checkAutomaticVersion(); });
  ok(automaticUpdateState().checkFailure === "server", "server failure has its own explanation");
  globalThis.fetch = (async () => ({ ok: true, json: async () => { throw Error("invalid JSON"); } })) as any;
  await act(async () => { await checkAutomaticVersion(); });
  ok(automaticUpdateState().checkFailure === "invalid", "invalid body has its own explanation");
  globalThis.fetch = (() => new Promise(() => {})) as any;
  await act(async () => { await checkAutomaticVersion(10); });
  ok(automaticUpdateState().checkFailure === "timeout", "bounded timeout is explained");
  globalThis.fetch = (async () => ({ ok: true, json: async () => ({ version: APP_VERSION }) })) as any;
  await act(async () => { await checkAutomaticVersion(); });
  ok(automaticUpdateState().checkFailure === "" && settings.text.includes("You’re up to date."), "successful retry clears recovery failure");
  ok(settings.el.querySelector('a[href="/auth/deployment-access"]') == null, "recovery action disappears after success");
  ok(beforeProtected === JSON.stringify(Object.fromEntries(Object.keys(legacy).map(k => [k, window.localStorage.getItem(k)]))), "all failure and retry paths preserve scores and drafts");
  banner.unmount();
  const savedOutcome = window.sessionStorage.getItem('bnn-update-result-v1');
  await act(async () => { banner = renderScreen(<RegisterSW />); await new Promise(resolve => setTimeout(resolve, 5)); });
  ok(automaticUpdateState().outcome?.status === 'success' && savedOutcome === window.sessionStorage.getItem('bnn-update-result-v1'), 're-entry restores the retained result without another success banner');
  ok(banner.text === '', 'retained historical success does not reappear as a pending update');
  settings.unmount(); banner.unmount(); globalThis.fetch = oldFetch;
  report("explicit update banner and status");
}
main().catch(error => { console.error(error); process.exitCode = 1; });

import { ok, report, renderScreen } from "./screen-harness";
import * as React from "react";
import { act } from "react";
import { APP_VERSION } from "./app-version";
import { reconcileUpdateGames, protectUpdateSession, updateBlockers, pendingUpdateScores, rememberUpdateRound } from "./update-safety";
import { updateState, setUpdateAvailable, dismissUpdate, checkForUpdate, applyAppUpdate, requestActivation, restoreUpdateResult, reportDeferredReload } from "./app-update";
import { RegisterSW } from "../components/register-sw";
import { UpdateChecker } from "../components/app-update-checker";

async function main() {
  window.localStorage.clear(); window.sessionStorage.clear();
  await reconcileUpdateGames(async () => null);
  const available = "999.0.261101";
  const oldFetch = globalThis.fetch;
  globalThis.fetch = (async () => ({ ok: true, json: async () => ({ version: available }) })) as any;
  let outcome: any = { kind: "bnn-update-result", accepted: false, blockers: [{ key: "tab:legacy", title: "Another BNN tab did not respond", action: "Finish and sync that tab's rounds, then close it and try again." }], message: "Update paused by another tab." };
  let sent = 0;
  const worker = { state: "installed", postMessage: (_message: string, ports: MessagePort[]) => { sent++; ports[0].postMessage(outcome); } } as unknown as ServiceWorker;
  const reg = { waiting: worker, installing: null, update: async (): Promise<void> => undefined };
  const events = new window.EventTarget();
  const sw = { controller: {}, register: async () => reg, getRegistration: async () => reg, addEventListener: events.addEventListener.bind(events), removeEventListener: events.removeEventListener.bind(events) };
  Object.defineProperty(navigator, "serviceWorker", { configurable: true, value: sw });
  let banner!: ReturnType<typeof renderScreen>;
  await act(async () => { banner = renderScreen(<RegisterSW />); await new Promise(resolve => setTimeout(resolve, 30)); });
  ok(banner.text.includes("A new version"), "real available banner renders");
  await act(async () => { banner.click("Update"); await new Promise(resolve => setTimeout(resolve, 30)); });
  ok(sent === 1, "real Update button reaches shared activation request");
  ok(banner.text.includes("Update paused") && !banner.text.includes("Updating…"), "veto produces an explicit result, not a silent reset");
  ok(banner.text.includes("Another BNN tab did not respond"), "veto names the blocking tab condition");
  banner.click("Details");
  ok(banner.text.includes("Finish and sync that tab"), "details shows the actual remediation from worker result");
  banner.click("Close details");
  banner.click("Dismiss");
  ok(!banner.el.querySelector("[data-update-notice]"), "Dismiss removes the actual banner");
  await act(async () => { await checkForUpdate(false); });
  ok(!banner.el.querySelector("[data-update-notice]"), "same release passive check respects dismissal");
  const settings = renderScreen(<UpdateChecker />);
  ok(settings.text.includes("App version") && settings.text.includes("Another BNN tab"), "Settings retains result and details after banner dismissal");
  await act(async () => { await checkForUpdate(true); });
  ok(!banner.el.querySelector("[data-update-notice]"), "manual Settings recheck also respects dismissal for the same release");
  act(() => setUpdateAvailable("999.1.261101"));
  ok(!!banner.el.querySelector("[data-update-notice]"), "different release can announce itself");
  outcome = { kind: "bnn-update-result", accepted: false, blockers: [], message: "The downloaded update could not be contacted. Check your connection." };
  await act(async () => { await applyAppUpdate(); });
  ok(banner.text.includes("Update did not complete") && banner.text.includes("Check your connection"), "communication failure is visible in actual banner");
  ok(banner.text.includes("Try again") && !banner.text.includes("Updating…"), "failed attempt leaves an explicit retry action");
  act(() => protectUpdateSession("game", "g", true, "Saturday at Francis Byrne", "947286"));
  const active = updateBlockers();
  ok(active.some(item => item.title.includes("Saturday at Francis Byrne") && item.title.includes("947286")), "active session checklist names game and code");
  ok(active.some(item => item.action.includes("organizer")), "active game explains who finishes it");
  const before = sent;
  await act(async () => { await applyAppUpdate(); });
  ok(sent === before, "blocked action never sends activation");
  ok(updateState().phase === "blocked" && updateState().blockers.some(item => item.title.includes("947286")), "blocked action provides current precise reasons");
  act(() => protectUpdateSession("game", "g", false));
  act(() => {
    rememberUpdateRound("older-round", { course: "Older saved round", played_at: "2026-10-30" });
    protectUpdateSession("round", "older-round", true);
  });
  ok(updateBlockers().some(item => item.title.includes("Older saved round") && item.title.includes("2026-10-30")), "older session without a label is identified from read-only metadata");
  await act(async () => { await reconcileUpdateGames(async () => null, async () => ({ course: "Verified round name", played_at: "2026-10-29" })); });
  ok(updateBlockers().some(item => item.title.includes("Verified round name")), "round reconciliation refreshes names without releasing protection");
  act(() => protectUpdateSession("round", "older-round", false));
  const prefix = "bnn_device_scores:person:tab:";
  const backup = { scores: [5], putts: [2], fairways: [true], penalties: [0], sand: [false] };
  window.localStorage.setItem(prefix + "bnn_game_scores_g_p", JSON.stringify(backup));
  window.localStorage.setItem("bnn_game_snap_g", JSON.stringify({ game: { name: "Francis Byrne", code: "947286", status: "ended" }, players: [{ id: "p", display_name: "Amit" }] }));
  const pending = updateBlockers();
  ok(pending.some(item => item.title.includes("947286") && item.title.includes("Amit") && item.title.includes("1 hole")), "pending checklist identifies game, player and count");
  ok(pending.some(item => item.action.includes("Sync now") && item.action.includes("reopen")), "pending ended-game edits explain sync and organizer correction path");
  ok(pendingUpdateScores(window.localStorage), "diagnostics do not clear pending scores");
  window.localStorage.setItem(prefix + "bnn_game_wm_g_p", JSON.stringify(backup));
  ok(!updateBlockers().some(item => item.key.startsWith("pending:")), "confirmed sync clears precise blocker");
  window.localStorage.setItem(prefix + "bnn_round_draft_v1", JSON.stringify({ round: { id: "r", course: "Berkshire Valley", played_at: "2026-10-31", status: "in_progress" } }));
  ok(updateBlockers().some(item => item.title.includes("Berkshire Valley") && item.title.includes("2026-10-31")), "unfinished round is named with date");
  ok(updateBlockers().some(item => item.action.includes("discard") && item.action.includes("unwanted")), "round remediation does not silently discard work");
  window.localStorage.removeItem(prefix + "bnn_round_draft_v1");

  const timeout = await requestActivation({ postMessage: () => undefined } as unknown as ServiceWorker, 20);
  ok(!timeout.accepted && timeout.confirmed === false && !!timeout.message?.includes("older version"), "unanswered request has explicit timeout and older-tab instructions");
  const unavailable = await requestActivation({ postMessage: () => { throw new Error("gone"); } } as unknown as ServiceWorker);
  ok(!unavailable.accepted && !!unavailable.message?.includes("contact"), "worker communication failure has explicit result");
  outcome = { kind: "bnn-update-result", accepted: true, blockers: [] };
  const accepted = await requestActivation(worker);
  ok(accepted.accepted, "accepted result is carried back from worker");
  await act(async () => { await applyAppUpdate(); });
  ok(updateState().phase === "reloading" && !updateState().message.includes("successfully"), "activation acceptance is not falsely reported as installed success");
  act(() => reportDeferredReload());
  ok(updateState().phase === "blocked" && updateState().message.includes("restarting is paused"), "deferred controller reload has explicit feedback");
  window.sessionStorage.setItem("bnn_update_attempt_v1", "different-from-installed");
  act(() => restoreUpdateResult());
  ok(updateState().phase === "failed" && updateState().message.includes(APP_VERSION), "reload into old version reports failure and installed version");
  window.sessionStorage.setItem("bnn_update_attempt_v1", APP_VERSION);
  act(() => restoreUpdateResult());
  ok(updateState().phase === "success" && updateState().message.includes(APP_VERSION), "only verified installed target reports success");
  act(() => setUpdateAvailable(APP_VERSION));
  ok(updateState().phase === "success" && !updateState().dismissed, "passive version check keeps verified success visible");
  banner.click("Dismiss");
  ok(!banner.el.querySelector("[data-update-notice]"), "success notice is dismissible too");
  act(() => setUpdateAvailable("999.2.261101"));
  ok(updateState().phase === "idle" && banner.text.includes("Update") && !banner.text.includes("Update installed"), "new release after success offers updating again");
  settings.unmount(); banner.unmount();
  globalThis.fetch = (async () => { throw new Error("offline"); }) as any;
  await checkForUpdate(true);
  ok(updateState().phase === "failed" && updateState().message.includes("connection"), "network failure has actionable feedback");
  globalThis.fetch = (() => new Promise(() => undefined)) as any;
  await checkForUpdate(true, 20);
  ok(updateState().phase === "failed" && updateState().message.includes("connection"), "unresponsive version endpoint ends with explicit feedback");
  setUpdateAvailable("999.3.261101");
  const originalDownload = reg.update;
  reg.update = () => new Promise<void>(() => undefined);
  await applyAppUpdate(20);
  ok(updateState().phase === "failed" && updateState().message.includes("download"), "unresponsive worker download cannot leave Updating indefinitely");
  reg.update = originalDownload;
  setUpdateAvailable("999.4.261101");
  const originalPost = worker.postMessage;
  worker.postMessage = () => undefined;
  await applyAppUpdate(20);
  ok(updateState().phase === "failed" && window.sessionStorage.getItem("bnn_update_attempt_v1") === "999.4.261101", "unconfirmed activation retains target so a late successful reload can still be verified");
  worker.postMessage = originalPost;
  globalThis.fetch = oldFetch;
  delete (navigator as any).serviceWorker;
  report("app update feedback");
}
main().catch(error => { console.error(error); process.exitCode = 1; });

/**
 * 212.40 — ONE-STEP CREATION, PHASE 2: the proof that the single server step (create_game_complete, 0219) stores
 * EXACTLY what today's two steps store. For every phase-1 case the game is created in one call, given what Create saved
 * plus the line-up the organizer ended with (lib/structure-behaviour), and what is stored is compared with the phase-1
 * golden record (ci/assert-structure-behaviour.sql). Rendered as ci/assert-create-game-complete.sql.
 */
import { structureCases, renderStructureSql, ORGANIZER, CLUB, MEMBER_USERS, type StructureCase } from "./structure-behaviour";

const q = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'`;
export function oneStepArgs(c: StructureCase) {
  const f = c.final;
  const game = { ...c.created.game, pairings: f.game.pairings ?? [] };
  const teams = f.players.filter((p) => p.team != null).map((p) => ({ player: p.id, team: p.team }));
  const groups = f.players.filter((p) => p.tee_group != null).map((p) => ({ player: p.id, group: p.tee_group }));
  const foursomes = Array.isArray(f.game.foursomes) && JSON.stringify(f.game.foursomes) !== JSON.stringify(c.created.game.foursomes) ? f.game.foursomes : null;
  return { game, players: c.created.players, teams, groups, foursomes };
}
export function renderCreateCompleteSql(cases: StructureCase[], golden: string): string {
  // reuse the phase-1 setup (organizer, members, club) so both tests stand on the same ground
  const setup = renderStructureSql([], "{}").split("create temp table")[0].split("begin;\n")[1];
  const asOrganizer = `perform set_config('request.jwt.claim.sub', '${ORGANIZER}', true); perform set_config('request.jwt.claims', '{"sub":"${ORGANIZER}","role":"authenticated"}', true); execute 'set local role authenticated';`;
  const blocks = cases.map((c) => {
    const a = oneStepArgs(c);
    return `-- ${c.id}
do $$ begin
  ${asOrganizer}
  perform public.create_game_complete(${q(a.game)}::jsonb, ${q(a.players)}::jsonb, ${q(a.teams)}::jsonb, ${q(a.groups)}::jsonb, ${a.foursomes ? `${q(a.foursomes)}::jsonb` : "null"}, true);
  execute 'reset role';
  insert into bnn_one_step_state(id, state) select '${c.id.replace(/'/g, "''")}', jsonb_build_object(
    'game', (select jsonb_build_object('teams', teams, 'pairings', pairings, 'foursomes', foursomes, 'allowance_pct', allowance_pct, 'team_score_mode', team_score_mode, 'skins_mode', skins_mode, 'scramble_mode', scramble_mode, 'scramble_team_size', scramble_team_size) from public.games where id = '${c.gameId}'),
    'players', (select jsonb_agg(jsonb_build_object('id', id, 'name', display_name, 'team', team, 'tee_group', tee_group, 'is_marker', is_marker, 'course_handicap', course_handicap) order by display_name) from public.game_players where game_id = '${c.gameId}'));
end $$;`;
  }).join("\n\n");
  return `-- assert-create-game-complete.sql — GENERATED by lib/create-complete-behaviour.test (212.40, one-step creation phase 2).
-- Do not edit by hand. Every phase-1 case is created in ONE call (create_game_complete, 0219) with the same choices the
-- organizer made over two steps; what is stored must equal the phase-1 golden record (copied below from
-- ci/assert-structure-behaviour.sql — the test fails if the two copies ever differ).
begin;
${setup.trim()}
create temp table bnn_one_step_state(id text primary key, state jsonb) on commit drop;

${blocks}

do $$
declare now_state jsonb := (select jsonb_object_agg(id, state) from bnn_one_step_state);
  golden jsonb := '${golden.replace(/'/g, "''")}';
  bad text;
begin
  select string_agg(k, ', ' order by k) into bad from (
    select k from jsonb_object_keys(golden) k where now_state -> k is distinct from golden -> k) d;
  if bad is not null then raise exception 'ONE-STEP CREATE DIFFERS from the two-step record for: %', bad; end if;
  raise notice 'CREATE_GAME_COMPLETE_PASS % cases: one call stores exactly what the two steps store', (select count(*) from jsonb_object_keys(golden));
end $$;
rollback;
`;
}

import { renderScreen, ok, report } from './screen-harness';
import * as React from 'react';
import { act } from 'react';
import { PhoneDiagnosticsPanel } from '@/components/phone-diagnostics';
import { recordPhoneDiagnostic, resetPhoneDiagnostics } from './phone-diagnostics';
import { APP_VERSION } from './app-version';

(async () => {
  resetPhoneDiagnostics(); window.localStorage.setItem('bnn_round_draft_v1', 'PENDING_SCORE');
  const screen = renderScreen(<PhoneDiagnosticsPanel />);
  const button = () => screen.el.querySelector('[data-export-diagnostics]') as HTMLButtonElement;
  ok(screen.el.textContent?.includes('Diagnostics & support'), 'every-member support panel is rendered');
  ok(button().textContent === 'Export diagnostic report', 'clear export action');
  ok(screen.el.textContent?.includes('Earlier app versions'), 'history limit is visible');
  act(() => recordPhoneDiagnostic('save.failed', { entityId: '123456' }));
  ok(screen.el.textContent?.includes('1 recent events'), 'live event count updates');
  const textarea = screen.el.querySelector('textarea')!;
  act(() => { Object.getOwnPropertyDescriptor(window.HTMLTextAreaElement.prototype, 'value')!.set!.call(textarea, 'The scorecard stalled after reconnecting.'); textarea.dispatchEvent(new Event('input', { bubbles: true })); });
  ok(screen.text.includes('41/500'), 'typed problem updates the counter');
  let release: (() => void) | undefined, shared: ShareData | undefined;
  Object.defineProperty(navigator, 'canShare', { configurable: true, value: () => true });
  Object.defineProperty(navigator, 'share', { configurable: true, value: async (data: ShareData) => { shared = data; await new Promise<void>(resolve => { release = resolve; }); } });
  await act(async () => { button().click(); for (let i = 0; i < 12; i++) await Promise.resolve(); });
  ok(button().disabled && button().textContent === 'Preparing…', 'export shows busy state');
  ok(shared?.files?.[0]?.name.startsWith('BNN-diagnostics-'), 'phone share sheet receives named JSON report');
  const file = shared?.files?.[0];
  const json = file ? JSON.parse(await file.text()) : {};
  ok(json.schema === 'bnn-phone-diagnostics/v1', 'export has schema');
  ok(json.events?.some((e: { event: string }) => e.event === 'save.failed'), 'actual recorded event is exported');
  ok(json.userDescription === 'The scorecard stalled after reconnecting.', 'typed context reaches the shared JSON');
  ok(!JSON.stringify(json.events).includes('scorecard stalled'), 'typed context is never added to automatic history');
  ok(json.updateStatus && 'lastOutcome' in json.updateStatus, 'report includes structured version-check and last-update status');
  ok(!Object.values(window.localStorage).some(v => String(v).includes('scorecard stalled')), 'typed context never persists to local storage');
  ok(!JSON.stringify(json).includes('PENDING_SCORE'), 'saved score content is not exported');
  await act(async () => { release?.(); for (let i = 0; i < 6; i++) await Promise.resolve(); });
  ok(!button().disabled && screen.el.textContent?.includes('Report shared or saved'), 'success result is visible and retry available');
  Object.defineProperty(navigator, 'share', { configurable: true, value: async () => { throw new DOMException('cancel', 'AbortError'); } });
  await act(async () => { button().click(); for (let i = 0; i < 12; i++) await Promise.resolve(); });
  ok(!button().disabled && screen.el.textContent?.includes('Export canceled'), 'share cancellation is explicit, not success');
  let downloads = 0;
  Object.defineProperty(navigator, 'canShare', { configurable: true, value: () => false });
  const create = URL.createObjectURL, revoke = URL.revokeObjectURL;
  URL.createObjectURL = () => 'blob:test'; URL.revokeObjectURL = () => {};
  const click = window.HTMLAnchorElement.prototype.click;
  window.HTMLAnchorElement.prototype.click = function() { downloads++; };
  await act(async () => { button().click(); for (let i = 0; i < 12; i++) await Promise.resolve(); });
  ok(downloads === 1 && screen.el.textContent?.includes('Report download requested'), 'download fallback is observable');
  Object.defineProperty(navigator, 'canShare', { configurable: true, value: () => { throw new Error('PRIVATE_EXPORT_ERROR'); } });
  await act(async () => { button().click(); for (let i = 0; i < 12; i++) await Promise.resolve(); });
  ok(!button().disabled && screen.el.textContent?.includes('Could not export'), 'failure leaves retry available');
  ok(!screen.el.textContent?.includes('PRIVATE_EXPORT_ERROR'), 'raw exception never appears in support UI');
  ok(window.localStorage.getItem('bnn_round_draft_v1') === 'PENDING_SCORE', 'all export paths leave pending scores intact');
  const originalFetch = globalThis.fetch;
  globalThis.fetch = (async () => ({ ok: true, json: async () => ({ version: APP_VERSION }) })) as any;
  let reportedVersion = APP_VERSION;
  Object.defineProperty(navigator, 'serviceWorker', { configurable: true, value: { getRegistration: async () => ({ active: { state: 'activated' }, waiting: null }), controller: { state: 'activated', postMessage: (_message: unknown, ports: MessagePort[]) => ports[0].postMessage({ version: reportedVersion }) } } });
  await act(async () => { const details = screen.el.querySelector('details')!; details.open = true; details.dispatchEvent(new Event('toggle')); await new Promise(resolve => setTimeout(resolve, 30)); });
  // Wait for the postMessage response after React commits the open state.
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 30)); });
  ok(screen.text.includes('Matches installed app'), 'opening the panel queries and displays the actual controlling worker');
  await act(async () => { screen.click('Refresh summary'); await new Promise(resolve => setTimeout(resolve, 30)); });
  ok(screen.text.includes('Succeeded') && screen.text.includes('Available on this device'), 'refresh reaches version check and renders its outcome with storage status');
  reportedVersion = '212.99.261112';
  await act(async () => { screen.click('Refresh summary'); await new Promise(resolve => setTimeout(resolve, 30)); });
  ok(screen.text.includes('Differs from installed app') && !screen.text.includes('Matches installed app'), 'refresh replaces a stale healthy summary with a version mismatch');
  reportedVersion = APP_VERSION;
  await act(async () => { screen.click('Refresh summary'); await new Promise(resolve => setTimeout(resolve, 30)); });
  ok(screen.text.includes('Matches installed app') && !screen.text.includes('Differs from installed app'), 'summary round trip restores aligned status');
  Object.defineProperty(navigator, 'serviceWorker', { configurable: true, value: { getRegistration: async () => { throw Error('PRIVATE_REGISTRATION_ERROR'); } } });
  await act(async () => { screen.click('Refresh summary'); await new Promise(resolve => setTimeout(resolve, 30)); });
  ok(screen.text.includes('Could not read') && !screen.text.includes('PRIVATE_REGISTRATION_ERROR'), 'worker lookup failure is explicit and excludes raw exception');
  globalThis.fetch = originalFetch;
  URL.createObjectURL = create; URL.revokeObjectURL = revoke; window.HTMLAnchorElement.prototype.click = click;
  screen.unmount(); const fresh = renderScreen(<PhoneDiagnosticsPanel />);
  ok((fresh.el.querySelector('textarea') as HTMLTextAreaElement).value === '', 'problem text does not survive a fresh panel');
  fresh.unmount(); resetPhoneDiagnostics();
  report('phone diagnostic export');
})().catch(error => { console.error(error); process.exitCode = 1; });

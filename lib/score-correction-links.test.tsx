import { ok, report, renderScreen } from "./screen-harness";
import React, { act, useState } from "react";
import { ScoreCorrectionLink } from "../components/score-correction-link";
import { useScoreCorrectionNavigation } from "../components/score-correction-navigation";
import { UpdateBlockerList } from "../components/app-update-status";
import { parseScoreCorrection, scoreCorrectionHref, scoreClubName } from "./score-correction-links";
import { rememberUpdateGame, rememberUpdateRound, protectUpdateSession, reconcileUpdateGames, updateBlockers } from "./update-safety";
import type { Round } from "./golf";
const gameA = "12300000-0000-0000-0000-000000000001", gameB = "12300000-0000-0000-0000-000000000002";
const roundId = "12300000-0000-0000-0000-000000000003";
const clubs = [{ id: "club-a" }, { id: "club-b" }];
const round = { id: roundId, group_id: "club-b", group_name: "Test Club", course: "Saved course", holes: [], status: "in_progress" } as unknown as Round;
let readGame = async (id: string): Promise<{ id: string; group_id: string | null } | null> => ({ id, group_id: id === gameA ? "club-a" : "club-b" });
let readRound = async (_id: string): Promise<Round | null> => round;
function Host({ ready = true }: { ready?: boolean }) {
  const [club, setClub] = useState("club-a"), [item, setItem] = useState("Settings"), [error, setError] = useState("");
  useScoreCorrectionNavigation({ ready, userId: "owner", groups: clubs, readGame: id => readGame(id), readRound: id => readRound(id), selectClub: setClub, openGame: id => setItem(`Game ${id}`), openRound: r => setItem(`Round ${r.id || r.draft_session_id} ${r.course}`), reportError: setError });
  return <div><div data-current>{club} · {item}</div><div role="alert">{error}</div><button onClick={() => setItem("Settings")}>Back to Settings</button><ScoreCorrectionLink target={{ kind: "game", id: gameA }}>Open A</ScoreCorrectionLink><ScoreCorrectionLink target={{ kind: "game", id: gameB }}>Open TST05</ScoreCorrectionLink><ScoreCorrectionLink target={{ kind: "round", id: roundId }}>Resume round</ScoreCorrectionLink></div>;
}
async function click(view: ReturnType<typeof renderScreen>, label: string) { await act(async () => { const target = Array.from(view.el.querySelectorAll<HTMLElement>("a,button")).find(el => el.textContent === label)!;
    target.dispatchEvent(new window.MouseEvent("click", { bubbles: true, cancelable: true })); await new Promise(resolve => setTimeout(resolve, 5)); }); }
async function main() {
  window.localStorage.clear(); await reconcileUpdateGames(async () => null);
  ok(parseScoreCorrection(`?scoreGame=${gameA}`)?.id === gameA, "game ID deep link parses independently of six-digit codes");
  ok(parseScoreCorrection(`?scoreRound=${roundId}`)?.kind === "round", "personal round ID deep link parses");
  ok(parseScoreCorrection("?scoreGame=TST05") === null, "code is never mistaken for database ID");
  ok(parseScoreCorrection("?scoreRound=../../secret") === null, "malformed external target rejected");
  ok(scoreCorrectionHref({ kind: "game", id: gameB }).includes(gameB), "anchor uses exact game ID");
  ok(scoreClubName({ group_name: "Main" }) === "Club: Main", "club is explicit");
  ok(scoreClubName({ group_id: null }, true).includes("no club"), "unaffiliated personal round is labelled accurately");
  ok(scoreClubName().includes("not yet available"), "unknown club is not guessed from current picker");
  rememberUpdateGame(gameB, { name: "Test Fourball", code: "TST05", group_id: "club-b", group_name: "Test Club" });
  protectUpdateSession("game", gameB, true);
  let blocker = updateBlockers().find(b => b.key === `game:${gameB}`)!;
  ok(blocker.target?.id === gameB && blocker.club === "Club: Test Club", "game warning carries actual target and club metadata");
  let view = renderScreen(<UpdateBlockerList blockers={[blocker]} />);
  ok(view.text.includes("Club: Test Club") && view.el.querySelector('a')?.getAttribute('href') === `/?scoreGame=${gameB}`, "actual warning renders club and actionable anchor"); view.unmount();
  protectUpdateSession("game", gameB, false);
  const prefix = "bnn_device_scores:u:t:";
  window.localStorage.setItem(`${prefix}bnn_game_scores_${gameB}_player`, JSON.stringify({ scores: [5] }));
  blocker = updateBlockers().find(b => b.key.startsWith("pending:"))!;
  ok(blocker.target?.id === gameB && blocker.club === "Club: Test Club", "pending player outbox links to the same game and club");
  window.localStorage.removeItem(`${prefix}bnn_game_scores_${gameB}_player`);
  window.localStorage.setItem(`${prefix}bnn:altshot-side-drafts:${gameB}`, JSON.stringify([{ holeIndex: 1 }]));
  ok(updateBlockers().find(b => b.key.startsWith("pending:"))?.target?.id === gameB, "team draft links to source game");
  window.localStorage.removeItem(`${prefix}bnn:altshot-side-drafts:${gameB}`);
  rememberUpdateRound(roundId, { course: "Saved course", group_id: "club-b", group_name: "Test Club" }); protectUpdateSession("round", roundId, true);
  blocker = updateBlockers().find(b => b.key === `round:${roundId}`)!;
  ok(blocker.target?.kind === "round" && blocker.club === "Club: Test Club", "personal round warning identifies its own club");
  protectUpdateSession("round", roundId, false);
  view = renderScreen(<Host />);
  await click(view, "Open TST05");
  ok(view.el.querySelector('[data-current]')?.textContent === `club-b · Game ${gameB}`, "actual link -> event -> authenticated lookup -> correct club and rendered game target");
  await click(view, "Back to Settings"); await click(view, "Open A");
  ok(view.el.querySelector('[data-current]')?.textContent === `club-a · Game ${gameA}`, "B to A switches back to source club");
  await click(view, "Back to Settings"); await click(view, "Open TST05");
  ok(view.el.querySelector('[data-current]')?.textContent === `club-b · Game ${gameB}`, "A -> B -> A/re-entry keeps exact target");
  await click(view, "Back to Settings"); await click(view, "Resume round");
  ok(view.el.querySelector('[data-current]')?.textContent?.includes(`club-b · Round ${roundId} Saved course`), "personal round opens exact loaded draft in its club");
  readGame = async () => null; await click(view, "Open A");
  ok(view.text.includes("could not be opened") && view.el.querySelector('[data-current]')?.textContent?.includes("Round"), "missing/RLS-hidden game gives explanation and keeps current screen");
  readGame = async id => ({ id, group_id: "inaccessible" }); await click(view, "Open A");
  ok(view.text.includes("do not currently have access"), "inaccessible club is not silently substituted");
  readGame = async id => ({ id, group_id: null }); await click(view, "Open A");
  ok(view.text.includes("club could not be determined"), "unknown game club cannot open under wrong club");
  readRound = async () => ({ ...round, group_id: null }); await click(view, "Resume round");
  ok(view.el.querySelector('[data-current]')?.textContent?.includes("Round"), "personal round without club remains openable");
  let finish!: (data: { id: string; group_id: string } | null) => void;
  readGame = () => new Promise(resolve => { finish = resolve; }); await click(view, "Open A");
  readRound = async () => round; await click(view, "Resume round");
  await act(async () => { finish({ id: gameA, group_id: "club-a" }); });
  ok(view.el.querySelector('[data-current]')?.textContent?.includes("Round"), "late older click cannot override newer navigation");
  view.unmount();
  readGame = async id => ({ id, group_id: "club-b" });
  window.history.replaceState({}, "", `/?scoreGame=${gameB}`);
  await act(async () => { view = renderScreen(<Host />); await new Promise(resolve => setTimeout(resolve, 5)); });
  ok(view.el.querySelector('[data-current]')?.textContent === `club-b · Game ${gameB}`, "opening/copying anchor cold resolves exact target");
  ok(!window.location.search.includes("scoreGame"), "startup target consumed once"); view.unmount();
  window.history.replaceState({}, "", "/");
  report("score correction links");
}
main().catch(error => { console.error(error); process.exitCode = 1; });

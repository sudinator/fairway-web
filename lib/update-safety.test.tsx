import { ok, report, renderScreen } from "./screen-harness";
import * as React from "react";
import { act } from "react";
import { checkScoringDevice, releaseScoringDeviceRuntime } from "./scoring-device";
import { protectUpdateSession, updatesBlocked, pendingUpdateScores, reconcileUpdateGames, UPDATE_EVENT, updateInProgress, releaseUpdateInput } from "./update-safety";
import { useScoringUpdateProtection, useUpdateInputLock } from "../components/update-safety";
import { RegisterSW } from "../components/register-sw";
import { UpdateChecker } from "../components/app-update-checker";
import { updateHandshake } from "./update-handshake";

async function main() {
  const storage = window.localStorage;
  storage.clear();
  ok(updatesBlocked(), "startup cannot offer update before device recovery");
  await checkScoringDevice({ rpc: async () => ({ data: { active: true }, error: null }) }, "update-test");
  ok(updatesBlocked(), "device ready alone does not finish bootstrap verification");
  await reconcileUpdateGames(async () => null);
  ok(!updatesBlocked(), "no session permits update");
  for (const kind of ["game", "round"] as const) {
    protectUpdateSession(kind, "live", true);
    ok(updatesBlocked(), `${kind}: active even with all scores synced`);
    await reconcileUpdateGames(async () => null);
    ok(updatesBlocked(), `${kind}: failed read does not end session`);
    protectUpdateSession(kind, "live", false);
    ok(!updatesBlocked(), `${kind}: confirmed finish/discard releases`);
  }
  const Session = ({ blocked }: { blocked: boolean }) => { useScoringUpdateProtection("game", "hook", blocked); return <div>Scorecard</div>; };
  let card = renderScreen(<Session blocked />);
  ok(updatesBlocked(), "mounted scoring card blocks");
  card.unmount();
  ok(updatesBlocked(), "leaving scorecard retains durable protection");
  await reconcileUpdateGames(async () => ({ status: "active" }));
  ok(updatesBlocked(), "active server result retains protection");
  await reconcileUpdateGames(async () => ({ missing: true }));
  ok(updatesBlocked(), "missing/RLS-hidden row is not evidence of completion");
  await reconcileUpdateGames(async () => ({ status: "ended" }));
  ok(!updatesBlocked(), "server finish while elsewhere releases clean session");
  card = renderScreen(<Session blocked />); card.unmount();
  ok(updatesBlocked(), "reopening ended game reinstates protection");
  protectUpdateSession("game", "hook", false);
  protectUpdateSession("game", "reopen-race", true);
  let finishRead!: (value: { status: string }) => void;
  const delayedRead = reconcileUpdateGames(() => new Promise(resolve => { finishRead = resolve; }));
  protectUpdateSession("game", "reopen-race", true);
  finishRead({ status: "ended" });
  await delayedRead;
  ok(updatesBlocked(), "stale end-of-game read cannot release a reopened session");
  protectUpdateSession("game", "reopen-race", false);
  const prefix = "bnn_device_scores:other-user:other-tab:";
  const scores = { scores: [5], putts: [2], fairways: [true], penalties: [0], sand: [false] };
  storage.setItem(prefix + "bnn_game_scores_g_p", JSON.stringify(scores));
  ok(pendingUpdateScores(storage) && updatesBlocked(), "another token's offline score blocks browser update");
  await reconcileUpdateGames(async () => ({ status: "ended" }));
  ok(updatesBlocked(), "ending game cannot override unsynced score");
  storage.setItem(prefix + "bnn_game_wm_g_p", JSON.stringify(scores));
  ok(!updatesBlocked(), "server acknowledgement releases final pending score");
  storage.setItem(prefix + "bnn_game_scores_g_p", JSON.stringify({ ...scores, scores: [null] }));
  ok(updatesBlocked(), "pending intentional score deletion also blocks");
  storage.removeItem(prefix + "bnn_game_scores_g_p");
  storage.setItem(prefix + "bnn:altshot-side-drafts:g", JSON.stringify([{ holeIndex: 2, strokes: 4 }]));
  ok(updatesBlocked(), "alternate shot outbox blocks");
  storage.setItem(prefix + "bnn:altshot-side-drafts:g", "[]");
  ok(!updatesBlocked(), "acknowledged alternate shot releases");
  storage.setItem(prefix + "bnn_round_draft_v1", JSON.stringify({ round: { id: "personal", status: "in_progress" } }));
  ok(updatesBlocked(), "synced personal round still in progress blocks");
  storage.removeItem(prefix + "bnn_round_draft_v1");
  storage.setItem(prefix + "bnn_edit_round:old", "{}");
  ok(updatesBlocked(), "unsaved historical-round edits block");
  storage.removeItem(prefix + "bnn_edit_round:old");
  storage.setItem(prefix + "bnn_game_scores_broken", "{");
  ok(updatesBlocked(), "corrupt score storage fails closed");
  storage.removeItem(prefix + "bnn_game_scores_broken");

  let clicked = 0;
  const Entry = () => { useUpdateInputLock(); return <button onClick={() => clicked++}>Enter score</button>; };
  const entry = renderScreen(<Entry />);
  entry.click("Enter score");
  ok(clicked === 1, "normal score input remains available");
  const h = updateHandshake();
  let response: any;
  const ask = (requestId: string) => h.receive({ data: { kind: "bnn-update-check", requestId }, ports: [{ postMessage: (v: any) => { response = v; } }] } as any);
  protectUpdateSession("game", "race", true); ask("blocked");
  ok(response.ready === false && !updateInProgress(), "active page vetoes worker and keeps editing available");
  protectUpdateSession("game", "race", false); ask("ready");
  ok(response.ready === true && updateInProgress(), "clean page acknowledges and freezes new input");
  entry.click("Enter score");
  ok(clicked === 1, "activation handshake blocks new score input in actual hook");
  h.receive({ data: { kind: "bnn-update-release", requestId: "wrong" } } as any);
  ok(updateInProgress(), "unrelated cancellation cannot release handshake");
  h.receive({ data: { kind: "bnn-update-release", requestId: "ready" } } as any);
  ok(!updateInProgress(), "worker veto releases clean page's input");
  h.dispose();
  entry.click("Enter score");
  ok(clicked === 2, "cancelled activation restores score input");
  entry.unmount();

  // Current update UI remains available through game start/end/re-entry.
  // Legacy safety helpers above are retained compatibility tests, not live gates.
  const oldFetch = globalThis.fetch;
  globalThis.fetch = (async () => ({ ok: true, json: async () => ({ version: "999.0.261101" }) })) as any;
  let banner: ReturnType<typeof renderScreen>;
  await act(async () => { banner = renderScreen(<RegisterSW />); await new Promise(resolve => setTimeout(resolve, 20)); });
  ok(banner!.text.includes("Update now"), "new version offers an explicit update banner");
  act(() => protectUpdateSession("game", "render", true));
  ok(banner!.text.includes("Update now"), "active game does not hide update action");
  const settings = renderScreen(<UpdateChecker />);
  ok(settings.text.includes("Update now") && !settings.text.includes("Updates are paused"), "Settings ignores historical session blockers");
  act(() => protectUpdateSession("game", "render", false));
  ok(banner!.text.includes("Update now"), "ending a game retains the same update action");
  act(() => protectUpdateSession("game", "render", true));
  ok(banner!.text.includes("Update now"), "reopening a game never reinstates an update gate");
  act(() => protectUpdateSession("game", "render", false));
  settings.unmount(); banner!.unmount(); globalThis.fetch = oldFetch;
  releaseUpdateInput(); releaseScoringDeviceRuntime();
  // Last case deliberately poisons this runtime's storage safety latch.
  const original = window.Storage.prototype.setItem;
  window.Storage.prototype.setItem = () => { throw new Error("quota"); };
  protectUpdateSession("round", "quota", true);
  window.Storage.prototype.setItem = original;
  ok(updatesBlocked(), "failed durable protection write cannot permit update");
  report("update safety");
}
main().catch(e => { console.error(e); process.exitCode = 1; });
